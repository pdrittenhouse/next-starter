#!/usr/bin/env node
/**
 * Generate subset companions for this repo's self-hosted webfonts.
 *
 * Writes, for every `src/fonts/**\/*.woff2` that is not already a subset:
 *
 *   - `<name>.subset.woff2`, carrying only the characters in `lib/font-subset.mjs`'s ranges
 *   - `src/scss/generated/_font-subset-ranges.scss`, the matching `unicode-range` values
 *
 * The SCSS is generated rather than written by hand so the range the browser is told about and
 * the glyphs the file actually contains cannot drift apart. Drift in one direction ships dead
 * bytes; in the other it ships tofu. Neither is visible in a build log.
 *
 * DORMANT BY DESIGN. As of 2026-11-05 this repo self-hosts no text webfont: every Typekit and
 * Google Fonts line in `src/scss/printing/_type.scss` is commented out, and the only
 * `@font-face` rules in the built CSS are icon families. So this exits early and reports
 * nothing to do. It is wired now rather than later so the first self-hosted face picks it up
 * without anyone having to rediscover that the framework solved this -- see TODO.md §1d.
 *
 * Icon fonts are deliberately out of scope: they live in `node_modules` or `public/`, not
 * `src/fonts/`, and their glyph set is decided by which `.bi-*` / `.fa-*` rules survive the
 * build, not by a Unicode range. The framework subsets those with a separate tool that has to
 * run after the purge.
 *
 * Idempotent: re-running overwrites. Safe to run before every build.
 *
 *   node scripts/gen-font-subsets.mjs [--dry-run]
 */

import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  subsetBuffer,
  subsetFilename,
  subsetUnicodeRange,
  complementUnicodeRange,
} from './lib/font-subset.mjs';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dryRun = process.argv.includes('--dry-run');

/** Every non-subset .woff2 under a directory, recursively. */
async function fontFiles(dir) {
  const out = [];
  let entries;
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch {
    return out;
  }
  for (const e of entries) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) {
      out.push(...await fontFiles(full));
    } else if (/\.woff2$/i.test(e.name) && !/\.subset\.woff2$/i.test(e.name)) {
      out.push(full);
    }
  }
  return out;
}

const fontsDir = path.join(repoRoot, 'src/fonts');
if (!existsSync(fontsDir)) {
  console.log('[gen:fonts] no src/fonts — nothing to do');
  process.exit(0);
}

const files = await fontFiles(fontsDir);
if (files.length === 0) {
  console.log('[gen:fonts] src/fonts holds no .woff2 — nothing to do (dormant, see the docblock)');
  process.exit(0);
}

let totalBefore = 0;
let totalAfter = 0;
const rows = [];

for (const file of files) {
  const buf = await readFile(file);
  let sub;
  try {
    sub = await subsetBuffer(buf);
  } catch (err) {
    // A font the subsetter cannot read must not fail the build: the full face still ships and
    // the page still renders. But it is reported, because a silently un-subset font is a
    // regression that only shows as bytes.
    console.warn(`[gen:fonts] SKIPPED ${path.relative(repoRoot, file)}: ${err.message}`);
    continue;
  }

  // A "subset" that saved nothing means the font was already minimal, or the ranges cover
  // everything it has. Writing it anyway would add a request for no benefit.
  if (sub.length >= buf.length) {
    console.warn(
      `[gen:fonts] SKIPPED ${path.relative(repoRoot, file)}: subset is not smaller `
      + `(${sub.length} >= ${buf.length} B) — already minimal?`
    );
    continue;
  }

  const target = subsetFilename(file);
  if (!dryRun) await writeFile(target, sub);
  totalBefore += buf.length;
  totalAfter += sub.length;
  rows.push({ name: path.relative(repoRoot, file), before: buf.length, after: sub.length });
}

// The SCSS half: the ranges the CSS must declare for the files just written.
const scssDir = path.join(repoRoot, 'src/scss/generated');
const scssPath = path.join(scssDir, '_font-subset-ranges.scss');
const scss = `// GENERATED by scripts/gen-font-subsets.mjs — do not edit.
//
// The \`unicode-range\` values that pair a subset face with its full-face complement. Generated
// from scripts/lib/font-subset.mjs so the range the browser is told about and the glyphs the
// subset file actually contains cannot disagree.
//
// The two ranges partition the Unicode codespace exactly: every codepoint belongs to one face
// and no codepoint to both. An overlap would let the browser fetch the full face to render an
// ASCII letter; a gap would leave a character with no face in the family at all.

$font-subset-range: "${subsetUnicodeRange()}";
$font-subset-complement: "${complementUnicodeRange()}";
`;

if (!dryRun) {
  await mkdir(scssDir, { recursive: true });
  await writeFile(scssPath, scss);
}

const kb = (n) => `${(n / 1024).toFixed(1)} KB`;
console.log(`[gen:fonts] ${repoRoot}${dryRun ? '  (dry run)' : ''}`);
for (const r of rows) {
  const pct = (100 * (1 - r.after / r.before)).toFixed(1);
  console.log(`  ${r.name}\n      ${kb(r.before)} -> ${kb(r.after)}  (-${pct}%)`);
}
if (rows.length) {
  const pct = (100 * (1 - totalAfter / totalBefore)).toFixed(1);
  console.log(`  total: ${kb(totalBefore)} -> ${kb(totalAfter)}  (-${pct}%)`);
}
console.log(`  ranges: ${path.relative(repoRoot, scssPath)}`);
